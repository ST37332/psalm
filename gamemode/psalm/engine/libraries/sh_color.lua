function COLOR:Blend(other, mode, t)
    t = t or 0.5
    mode = (mode or "normal"):lower()

    if mode == "multiply" then
        return Color(self.r * other.r / 255, self.g * other.g / 255,
                     self.b * other.b / 255, self.a or 255)
    elseif mode == "screen" then
        return Color(255 - (255 - self.r) * (255 - other.r) / 255,
                     255 - (255 - self.g) * (255 - other.g) / 255,
                     255 - (255 - self.b) * (255 - other.b) / 255,
                     self.a or 255)
    elseif mode == "add" then
        return Color(clamp(self.r + other.r, 0, 255),
                     clamp(self.g + other.g, 0, 255),
                     clamp(self.b + other.b, 0, 255), self.a or 255)
    elseif mode == "subtract" then
        return Color(clamp(self.r - other.r, 0, 255),
                     clamp(self.g - other.g, 0, 255),
                     clamp(self.b - other.b, 0, 255), self.a or 255)
    elseif mode == "difference" then
        return Color(math.abs(self.r - other.r),
                     math.abs(self.g - other.g),
                     math.abs(self.b - other.b), self.a or 255)
    elseif mode == "overlay" then
        local function f(a, b)
            a, b = a / 255, b / 255
            return (a < 0.5 and 2 * a * b or 1 - 2 * (1 - a) * (1 - b)) * 255
        end
        return Color(f(self.r, other.r), f(self.g, other.g), f(self.b, other.b), self.a or 255)
    end
    return self:Lerp(other, t)
end

function COLOR:Mult(other)
    return self:Blend(other, "multiply")
end

function color:Average(colors)
    if not colors or #colors == 0 then return Color(0, 0, 0) end
    local r, g, b, a = 0, 0, 0, 0
    for _, c in ipairs(colors) do
        r = r + c.r; g = g + c.g; b = b + c.b; a = a + (c.a or 255)
    end
    local n = #colors
    return Color(r / n, g / n, b / n, a / n)
end

function color:SortByHue(palette)
    local copy = {}
    for i, c in ipairs(palette) do
        local h = c:ToHSL()
        copy[i] = { c = c, h = h }
    end
    table.sort(copy, function(a, b) return a.h < b.h end)
    local out = {}
    for i, v in ipairs(copy) do out[i] = v.c end
    return out
end

function color:PickDistinct(count, minDelta)
    count = count or 5
    minDelta = minDelta or 25
    local out = {}
    local tries = 0
    while #out < count and tries < count * 200 do
        tries = tries + 1
        local c = Color(math.random(0, 255), math.random(0, 255), math.random(0, 255))
        local ok = true
        for _, e in ipairs(out) do
            if c:DeltaE(e) < minDelta then ok = false; break end
        end
        if ok then out[#out + 1] = c end
    end
    return out
end

function color:RandomRGB()
