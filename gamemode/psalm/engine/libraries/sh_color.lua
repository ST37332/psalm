function color:FromHex(hex)
    if not hex or type(hex) ~= "string" then return end
    hex = hex:gsub("#", ""):gsub("%s", "")
    if #hex == 3 then
        hex = hex:gsub("(.)", "%1%1")
    end
    if #hex ~= 6 and #hex ~= 8 then return end
    return Color(
        tonumber(hex:sub(1, 2), 16),
        tonumber(hex:sub(3, 4), 16),
        tonumber(hex:sub(5, 6), 16),
        #hex == 8 and tonumber(hex:sub(7, 8), 16) or 255
    )
end

function color:Parse(str)
    if not str then return end
    if type(str) == "table" then return str end
    str = tostring(str):lower():gsub("%s", "")

    if color[str] and type(color[str]) == "table" and color[str].r then
        return color[str]
    end

    if str:sub(1, 1) == "#" or str:match("^%x%x%x%x%x%x") or str:match("^%x%x%x$") then
        return color:FromHex(str)
    end

    local r, g, b, a = str:match("(%d+)[,;]?()(%d+)[,;]?()(%d+)[,;]?()(%d*)")
    if r then
        return Color(tonumber(r), tonumber(g), tonumber(b),
            (a and a ~= "") and tonumber(a) or 255)
    end
end

COLOR = FindMetaTable('Color')

function COLOR:ToHex(includeAlpha)
    local r, g, b = floor(self.r + 0.5), floor(self.g + 0.5), floor(self.b + 0.5)
    if includeAlpha then
        return string.format("#%02X%02X%02X%02X", r, g, b, floor((self.a or 255) + 0.5))
    end
    return string.format("#%02X%02X%02X", r, g, b)
end

function COLOR:Lerp(other, t)
    return Color(
        clamp(self.r + (other.r - self.r) * t, 0, 255),
        clamp(self.g + (other.g - self.g) * t, 0, 255),
        clamp(self.b + (other.b - self.b) * t, 0, 255),
        clamp((self.a or 255) + ((other.a or 255) - (self.a or 255)) * t, 0, 255)
    )
end

function color:Gradient(c1, c2, steps)
    steps = math.max(2, steps or 10)
    local out = {}
    for i = 1, steps do
        out[i] = c1:Lerp(c2, (i - 1) / (steps - 1))
    end
    return out
end

function color:GradientMulti(colors, steps)
    if not colors or #colors < 2 then return {} end
    steps = math.max(2, steps or 10)
    local segs = #colors - 1
    local out = {}
    for i = 1, steps do
        local t = (i - 1) / (steps - 1) * segs
        local seg = clamp(floor(t) + 1, 1, segs)
        out[i] = colors[seg]:Lerp(colors[seg + 1], t - (seg - 1))
    end
    return out
end

local function RGBToXYZ(c)
    local function lin(v)
        v = v / 255
        return v > 0.04045 and pow((v + 0.055) / 1.055, 2.4) or (v / 12.92)
    end
    local r, g, b = lin(c.r), lin(c.g), lin(c.b)
    return {
        x = r * 0.4124564 + g * 0.3575761 + b * 0.1804375,
        y = r * 0.2126729 + g * 0.7151522 + b * 0.0721750,
        z = r * 0.0193339 + g * 0.1191920 + b * 0.9503041,
    }
end

local function XYZToLab(xyz)
    local function f(t)
        return t > 0.008856 and pow(t, 1/3) or (7.787 * t + 16/116)
    end
    local fx, fy, fz = f(xyz.x / 0.95047), f(xyz.y), f(xyz.z / 1.08883)
    return { L = 116*fy - 16, A = 500*(fx - fy), B = 200*(fy - fz) }
end

function COLOR:ToLab()
    return XYZToLab(RGBToXYZ(self))
end

function COLOR:DeltaE(other)
    local a, b = self:ToLab(), other:ToLab()
    return sqrt((a.L - b.L)^2 + (a.A - b.A)^2 + (a.B - b.B)^2)
end

function COLOR:Equal(other, tolerance)
    tolerance = tolerance or 2
    return self:DeltaE(other) <= tolerance
end

function COLOR:RelativeLuminance()
    local function f(v)
        v = v / 255
        return v <= 0.03928 and v / 12.92 or pow((v + 0.055) / 1.055, 2.4)
    end
    return 0.2126*f(self.r) + 0.7152*f(self.g) + 0.0722*f(self.b)
end

function COLOR:ContrastRatio(other)
    local l1 = self:RelativeLuminance()
    local l2 = other:RelativeLuminance()
    local hi, lo = math.max(l1, l2), math.min(l1, l2)
    return (hi + 0.05) / (lo + 0.05)
end

function COLOR:WcagLevel(bg)
    local r = self:ContrastRatio(bg)
    if r >= 7   then return "AAA"
    elseif r >= 4.5 then return "AA"
    elseif r >= 3   then return "AA-large"
    else return "fail" end
end

function COLOR:GetTextColor(dark, light)
    dark  = dark  or color.black
    light = light or color.white
    return self:RelativeLuminance() > 0.179 and dark or light
end

function COLOR:PerceivedBrightness()
    return (self.r * 299 + self.g * 587 + self.b * 114) / 1000
end

function COLOR:GetTemperature()
    return (self.r - self.b) / 255
end

function COLOR:IsWarm() return self:GetTemperature() >  0.1 end
function COLOR:IsCool() return self:GetTemperature() < -0.1 end

function COLOR:IsNeutral()
    local r, g, b = self.r, self.g, self.b
    return (math.abs(r - g) < 12) and (math.abs(g - b) < 12) and (math.abs(r - b) < 12)
end

function COLOR:IsBright()
    return self:PerceivedBrightness() >= 128
end

function COLOR:IsDark() return not self:IsBright() end

function COLOR:Complementary()
    local h, s, l = self:ToHSL()
    return HSLToColor((h + 180) % 360, s, l)
end

function COLOR:Analogous(offset)
    offset = offset or 30
    local h, s, l = self:ToHSL()
    return { HSLToColor((h - offset) % 360, s, l),
             HSLToColor((h + offset) % 360, s, l) }
end

function COLOR:Triadic()
    local h, s, l = self:ToHSL()
    return { HSLToColor((h + 120) % 360, s, l),
             HSLToColor((h + 240) % 360, s, l) }
end

function COLOR:Tetradic()
    local h, s, l = self:ToHSL()
    return { HSLToColor((h +  90) % 360, s, l),
             HSLToColor((h + 180) % 360, s, l),
             HSLToColor((h + 270) % 360, s, l) }
end

function COLOR:SplitComplementary(offset)
    offset = offset or 30
    local h, s, l = self:ToHSL()
    return { HSLToColor((h + 180 - offset) % 360, s, l),
             HSLToColor((h + 180 + offset) % 360, s, l) }
end

function COLOR:GenerateHarmony(count)
    count = math.max(2, count or 5)
    local h, s, l = self:ToHSL()
    local out = { self }
    for i = 1, count - 1 do
        local nh = (h + (360 / count) * i) % 360
        local nl = clamp(l + ((i % 2 == 0) and 0.12 or -0.12), 0.08, 0.92)
        out[#out + 1] = HSLToColor(nh, s, nl)
    end
    return out
end

function COLOR:RotateHue(deg)
    local h, s, l = self:ToHSL()
    return HSLToColor((h + deg) % 360, s, l)
end

function COLOR:Saturate(amount)
    local h, s, l = self:ToHSL()
    return HSLToColor(h, clamp(s + amount, 0, 1), l)
end

function COLOR:Desaturate(amount)
    return self:Saturate(-(amount or 0.2))
end

function COLOR:AdjustBrightness(amount)
    return Color(
        clamp(self.r + amount * 255, 0, 255),
        clamp(self.g + amount * 255, 0, 255),
        clamp(self.b + amount * 255, 0, 255),
        self.a or 255)
end

function COLOR:AdjustContrast(amount)
    local f = (259 * (amount * 255 + 255)) / (255 * (259 - amount * 255))
    local function adj(v) return clamp(f * (v - 128) + 128, 0, 255) end
    return Color(adj(self.r), adj(self.g), adj(self.b), self.a or 255)
end

function COLOR:ToPastel(amount)
    amount = amount or 0.5
    local h, s, l = self:ToHSL()
    return HSLToColor(h, s * (1 - amount), clamp(l + (1 - l) * amount * 0.7, 0, 1))
end

