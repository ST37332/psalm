function COLOR:SimulateBlindness(kind)
    local m = BLINDNESS_MATRICES[(kind or ""):lower()]
    if not m then return self end
    return Color(
        clamp(m[1][1]*self.r + m[1][2]*self.g + m[1][3]*self.b, 0, 255),
        clamp(m[2][1]*self.r + m[2][2]*self.g + m[2][3]*self.b, 0, 255),
        clamp(m[3][1]*self.r + m[3][2]*self.g + m[3][3]*self.b, 0, 255),
        self.a or 255)
end

function COLOR:ApproximateName()
    local best, bestD
    for k, v in pairs(color) do
        if type(v) == "table" and v.r and v.g and v.b then
            local d = self:DeltaE(v)
            if not bestD or d < bestD then
                best, bestD = k, d
            end
        end
    end
    return best, bestD
end

function COLOR:Pulse(speed, amount, time)
    speed  = speed  or 1
    amount = amount or 0.3
    time   = time   or RealTime()
    local h, s, l = self:ToHSL()
    local wobble = sin(time * math.pi * 2 * speed) * 0.5 + 0.5
    return HSLToColor(h, s, clamp(l + (wobble - 0.5) * amount, 0.02, 0.98))
end

function COLOR:ToHSV()
    local r, g, b = self.r / 255, self.g / 255, self.b / 255
    local mx, mn = math.max(r, g, b), math.min(r, g, b)
    local d = mx - mn
    local h
    if d == 0 then h = 0
    elseif mx == r then h = 60 * (((g - b) / d) % 6)
    elseif mx == g then h = 60 * ((b - r) / d + 2)
    else h = 60 * ((r - g) / d + 4) end
    return h, (mx == 0 and 0 or d / mx), mx
end

function HSVToColor(h, s, v)
    h = h % 360
    local c = v * s
    local x = c * (1 - math.abs((h / 60) % 2 - 1))
    local m = v - c
    local r, g, b
    if     h <  60 then r, g, b = c, x, 0
    elseif h < 120 then r, g, b = x, c, 0
    elseif h < 180 then r, g, b = 0, c, x
    elseif h < 240 then r, g, b = 0, x, c
    elseif h < 300 then r, g, b = x, 0, c
    else               r, g, b = c, 0, x end
    return Color(clamp((r + m) * 255, 0, 255),
                 clamp((g + m) * 255, 0, 255),
                 clamp((b + m) * 255, 0, 255))
end