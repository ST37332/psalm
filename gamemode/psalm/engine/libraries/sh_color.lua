end

function color:RandomHSL(sMin, sMax, lMin, lMax)
    sMin = sMin or 0.5; sMax = sMax or 1.0
    lMin = lMin or 0.35; lMax = lMax or 0.65
    return HSLToColor(
        math.random() * 360,
        sMin + math.random() * (sMax - sMin),
        lMin + math.random() * (lMax - lMin)
    )
end

function COLOR:RandomNear(tolerance)
    tolerance = tolerance or 20
    local dr = math.random(-tolerance, tolerance)
    local dg = math.random(-tolerance, tolerance)
    local db = math.random(-tolerance, tolerance)
    return Color(clamp(self.r + dr, 0, 255),
                 clamp(self.g + dg, 0, 255),
                 clamp(self.b + db, 0, 255), self.a or 255)
end

function color:FromTemperature(kelvin)
    local k = clamp(kelvin, 1000, 40000) / 100
    local r, g, b
    if k <= 66 then
        r = 255
        g = 99.4708025861 * math.log(k) - 161.1195681661
    else
        r = 329.698727446 * pow(k - 60, -0.1332047592)
        g = 288.1221695283 * pow(k - 60, -0.0755148492)
    end
    if k >= 66 then b = 255
    elseif k <= 19 then b = 0
    else b = 138.5177312231 * math.log(k - 10) - 305.0447927307 end
    return Color(clamp(r, 0, 255), clamp(g, 0, 255), clamp(b, 0, 255))
end

